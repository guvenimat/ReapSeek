CREATE SCHEMA IF NOT EXISTS catalog;

CREATE TABLE catalog.categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES catalog.categories (id),
    slug text NOT NULL UNIQUE,
    name text NOT NULL,
    path text NOT NULL UNIQUE,
    depth int NOT NULL CHECK (depth BETWEEN 0 AND 3),
    position int NOT NULL DEFAULT 0,
    image_kind text NOT NULL DEFAULT 'box'
);

CREATE INDEX categories_parent_idx ON catalog.categories (parent_id);

CREATE TABLE catalog.brands (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL UNIQUE
);

CREATE UNIQUE INDEX brands_name_idx ON catalog.brands (lower(name));

CREATE TABLE catalog.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    title text NOT NULL,
    brand_id bigint NOT NULL REFERENCES catalog.brands (id),
    category_id bigint NOT NULL REFERENCES catalog.categories (id),
    description text NOT NULL DEFAULT '',
    attributes jsonb NOT NULL DEFAULT '{}',
    status text NOT NULL DEFAULT 'draft',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    submitted_by_seller_id bigint,
    review_note text,
    CONSTRAINT products_status_check CHECK (status IN ('draft', 'pending_review', 'active', 'rejected', 'archived'))
);

CREATE INDEX products_category_idx ON catalog.products (category_id, status);
CREATE INDEX products_brand_idx ON catalog.products (brand_id);
CREATE INDEX products_updated_idx ON catalog.products (updated_at DESC, id DESC);
CREATE INDEX products_submitted_by_idx ON catalog.products (submitted_by_seller_id) WHERE submitted_by_seller_id IS NOT NULL;

CREATE TABLE catalog.product_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES catalog.products (id) ON DELETE CASCADE,
    position int NOT NULL,
    url text NOT NULL,
    alt text NOT NULL DEFAULT '',
    color text,
    UNIQUE (product_id, position)
);

CREATE TABLE catalog.product_variants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES catalog.products (id) ON DELETE CASCADE,
    sku text NOT NULL UNIQUE,
    options jsonb NOT NULL DEFAULT '{}',
    position int NOT NULL DEFAULT 0,
    UNIQUE (product_id, options)
);

CREATE TABLE catalog.offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id bigint NOT NULL,
    variant_id bigint NOT NULL REFERENCES catalog.product_variants (id) ON DELETE CASCADE,
    price numeric(12, 2) NOT NULL CHECK (price > 0),
    list_price numeric(12, 2) CHECK (list_price IS NULL OR list_price >= price),
    stock int NOT NULL DEFAULT 0 CHECK (stock >= 0),
    handling_days int NOT NULL DEFAULT 1 CHECK (handling_days BETWEEN 1 AND 10),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (seller_id, variant_id)
);

CREATE INDEX offers_variant_idx ON catalog.offers (variant_id);

CREATE TABLE catalog.seller_snapshots (
    id bigint PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL,
    city text NOT NULL DEFAULT '',
    status text NOT NULL,
    rating numeric(2, 1) NOT NULL DEFAULT 0
);

CREATE VIEW catalog.buy_box AS
SELECT DISTINCT ON (o.variant_id)
    o.variant_id, o.id AS offer_id, o.seller_id, o.price, o.list_price, o.stock, o.handling_days
FROM catalog.offers o
JOIN catalog.seller_snapshots s ON s.id = o.seller_id
WHERE o.status = 'active' AND o.stock > 0 AND s.status = 'active'
ORDER BY o.variant_id, o.price, s.rating DESC, o.handling_days, o.id;
