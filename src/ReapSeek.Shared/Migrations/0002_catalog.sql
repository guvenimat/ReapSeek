CREATE TABLE sellers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL UNIQUE,
    city text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    commission_rate numeric(5, 4) NOT NULL DEFAULT 0.15 CHECK (commission_rate >= 0 AND commission_rate < 1),
    rating numeric(2, 1) NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX sellers_name_idx ON sellers (lower(name));

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES categories (id),
    slug text NOT NULL UNIQUE,
    name text NOT NULL,
    path text NOT NULL UNIQUE,
    depth int NOT NULL CHECK (depth BETWEEN 0 AND 3),
    position int NOT NULL DEFAULT 0,
    image_kind text NOT NULL DEFAULT 'box'
);

CREATE INDEX categories_parent_idx ON categories (parent_id);

CREATE TABLE brands (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL UNIQUE
);

CREATE UNIQUE INDEX brands_name_idx ON brands (lower(name));

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    title text NOT NULL,
    brand_id bigint NOT NULL REFERENCES brands (id),
    category_id bigint NOT NULL REFERENCES categories (id),
    description text NOT NULL DEFAULT '',
    attributes jsonb NOT NULL DEFAULT '{}',
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'archived')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX products_category_idx ON products (category_id, status);
CREATE INDEX products_brand_idx ON products (brand_id);
CREATE INDEX products_updated_idx ON products (updated_at DESC, id DESC);

CREATE TABLE product_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    position int NOT NULL,
    url text NOT NULL,
    alt text NOT NULL DEFAULT '',
    UNIQUE (product_id, position)
);

CREATE TABLE product_variants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    sku text NOT NULL UNIQUE,
    options jsonb NOT NULL DEFAULT '{}',
    position int NOT NULL DEFAULT 0,
    UNIQUE (product_id, options)
);

CREATE TABLE offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id bigint NOT NULL REFERENCES sellers (id),
    variant_id bigint NOT NULL REFERENCES product_variants (id) ON DELETE CASCADE,
    price numeric(12, 2) NOT NULL CHECK (price > 0),
    list_price numeric(12, 2) CHECK (list_price IS NULL OR list_price >= price),
    stock int NOT NULL DEFAULT 0 CHECK (stock >= 0),
    handling_days int NOT NULL DEFAULT 1 CHECK (handling_days BETWEEN 1 AND 10),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (seller_id, variant_id)
);

CREATE INDEX offers_variant_idx ON offers (variant_id);

CREATE VIEW buy_box AS
SELECT DISTINCT ON (o.variant_id)
    o.variant_id, o.id AS offer_id, o.seller_id, o.price, o.list_price, o.stock, o.handling_days
FROM offers o
JOIN sellers s ON s.id = o.seller_id
WHERE o.status = 'active' AND o.stock > 0 AND s.status = 'active'
ORDER BY o.variant_id, o.price, s.rating DESC, o.handling_days, o.id;
